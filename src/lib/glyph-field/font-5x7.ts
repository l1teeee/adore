export function layoutWordMask(word: string, columns: number, rows: number): readonly number[] | null {
  for (const letter of word) if (!/^[A-Z]$/.test(letter)) throw new Error(`Invalid character: ${letter}`);
  const width = (line: string) => Math.max(0, line.length * 6 - 1);
  let lines = [word];
  if (width(word) + 2 > columns || 9 > rows) {
    const middle = Math.ceil(word.length / 2);
    lines = [word.slice(0, middle), word.slice(middle)];
  }
  const height = lines.length * 7 + lines.length - 1;
  if (height + 2 > rows || lines.some((line) => width(line) + 2 > columns)) return null;
  const top = Math.floor((rows - height) / 2);
  const mask: number[] = [];
  lines.forEach((line, lineIndex) => {
    const left = Math.floor((columns - width(line)) / 2);
    for (let i = 0; i < line.length; i++) {
      const glyph = FONT_5X7[line[i]];
      for (let row = 0; row < 7; row++) {
        for (let column = 0; column < 5; column++) {
          if (glyph[row] & (16 >> column)) mask.push((top + lineIndex * 8 + row) * columns + left + i * 6 + column);
        }
      }
    }
  });
  return mask;
}
